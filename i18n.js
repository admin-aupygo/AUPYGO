let currentLang = localStorage.getItem('aupygo_lang') || 'fr';

// Traduit une clé du dictionnaire dans la langue courante (avec repli sur le FR)
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key])
      || (I18N.fr && I18N.fr[key])
      || key;
}

// Applique les traductions à tous les éléments data-i18n / data-i18n-html /
// data-i18n-placeholder / data-i18n-title / data-i18n-aria du DOM.
function applyTranslations() {

  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });

  // Re-génère les portions dynamiques qui dépendent du forfait / de l'état,
  // pour qu'elles restent traduites après un changement de langue à la volée.
  if (typeof updatePlanUI === 'function') updatePlanUI();
  if (typeof applyMapRestrictions === 'function') applyMapRestrictions();

}
